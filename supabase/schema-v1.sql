-- ============ 留言 ============
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  event_slug text not null,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  user_name text not null default '匿名',
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now(),
  is_hidden boolean not null default false,
  report_count int not null default 0
);

create index if not exists comments_event_idx on public.comments (event_slug, created_at desc);
create index if not exists comments_user_idx on public.comments (user_id, created_at desc);

alter table public.comments enable row level security;

-- 任何人可以睇未隱藏嘅留言；用戶可以睇自己被隱藏嘅留言
create policy "公開可以睇未隱藏留言"
  on public.comments for select
  using (not is_hidden or user_id = auth.uid());

-- 只有登入用戶可以留言，而且只可以用自己 user_id
create policy "登入用戶可以留言"
  on public.comments for insert
  to authenticated
  with check (user_id = auth.uid());

-- 用戶可以刪除自己嘅留言
create policy "用戶可以刪除自己留言"
  on public.comments for delete
  using (user_id = auth.uid());

-- ============ 舉報 ============
create table if not exists public.comment_reports (
  comment_id bigint not null references public.comments (id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (comment_id, user_id)
);

alter table public.comment_reports enable row level security;

create policy "登入用戶可以舉報"
  on public.comment_reports for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "用戶可以睇自己舉報"
  on public.comment_reports for select
  using (user_id = auth.uid());

-- 舉報用 RPC：一個用戶對一條留言只可舉報一次；
-- 達到門檻（5）自動隱藏
create or replace function public.report_comment(c_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  already bigint;
begin
  select count(*) into already from comment_reports
  where comment_id = c_id and user_id = auth.uid();
  if already = 0 then
    insert into comment_reports (comment_id, user_id) values (c_id, auth.uid());
    update comments
      set report_count = report_count + 1
      where id = c_id;
    update comments
      set is_hidden = true
      where id = c_id and report_count >= 5;
  end if;
end;
$$;

grant execute on function public.report_comment(bigint) to authenticated;

-- ============ 活動（之一步 scraping 用） ============
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title_zh text not null,
  title_en text,
  venue_zh text not null,
  venue_en text,
  address_zh text,
  category text not null default '展覽',
  start_date date not null,
  end_date date not null,
  price_zh text,
  lat double precision,
  lng double precision,
  summary_zh text,
  summary_en text,
  tags text[] default '{}',
  source text not null default 'manual', -- manual | scrape | submission
  approved boolean not null default false, -- submission 要審核
  created_at timestamptz not null default now()
);

create index if not exists events_category_idx on public.events (category, end_date desc);

alter table public.events enable row level security;

-- 檔案公開：所有人可以睇已批准嘅活動
create policy "公開可以睇已批准活動"
  on public.events for select
  using (approved = true);

